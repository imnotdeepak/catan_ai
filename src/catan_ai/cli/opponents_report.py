"""Opponent-model prediction and identification on recorded games (OPP-025) -> reports/.

Replays a dataset split's games. One seat (the viewer, rotating by game)
runs the opponent model and scores every opponent decision that had a real
choice, before seeing it:

- next-action log loss and top-1 / top-3 accuracy of the mixture, against
  each single component and the uniform policy, by the opponent's true
  policy (AlphaBeta is not a component: a held-out policy);
- identification: the posterior weight on the component that is the
  opponent's true policy, after 10, 25 and 50 scored decisions.

Example:
    python -m catan_ai.cli.opponents_report --games 200 --workers 11
"""

import argparse
import math
import time
from collections import defaultdict
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
from typing import Any

import numpy as np

from catan_ai.arena import replay
from catan_ai.engine import CanonicalAction
from catan_ai.observations import Referee
from catan_ai.opponents.components import standard_components
from catan_ai.opponents.model import OpponentModel
from catan_ai.provenance import REPO_ROOT, provenance
from catan_ai.training.dataset import read_jsonl

TRUE_COMPONENT = {
    "catanatron:F": "value-function",
    "catanatron:W": "weighted",
    "catanatron:VP": "victory-point",
}
CHECKPOINTS = (10, 25, 50)


def track_game(job: tuple[dict[str, Any], int, str | None]) -> list[dict[str, Any]]:
    record, viewer, checkpoint = job
    model = OpponentModel(
        viewer, standard_components(checkpoint), worlds=2, likelihood_worlds=1, diagnostics=True
    )

    def observe(seat: int, referee: Referee, action: CanonicalAction) -> None:
        model.update(referee.observe(viewer))

    referee = replay(record, observe)
    model.update(referee.observe(viewer))
    for row in model.diagnostics or []:
        row["policy"] = record["seating"][row["seat"]]
        row["game"] = record["match_id"]
    return model.diagnostics or []


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data", type=Path, default=REPO_ROOT / "data" / "imitation-v3")
    parser.add_argument("--split", default="holdout")
    parser.add_argument("--games", type=int, default=200, help="0 = all")
    parser.add_argument("--model", default="champions/imitation-features-v3.pt")
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--report", type=Path, default=REPO_ROOT / "reports" / "opponents.md")
    args = parser.parse_args(argv)

    started = time.perf_counter()
    records = read_jsonl(args.data / args.split / "replays.jsonl.gz")
    # Spread over lineups: every k-th game.
    if args.games and args.games < len(records):
        step = len(records) / args.games
        records = [records[int(i * step)] for i in range(args.games)]
    jobs = [(r, i % 4, args.model) for i, r in enumerate(records)]
    with ProcessPoolExecutor(args.workers) as pool:
        rows = [row for part in pool.map(track_game, jobs, chunksize=2) for row in part]
    names = [c.name for c in standard_components(None)] + [f"model:{args.model}"]

    by_policy: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        by_policy[row["policy"]].append(row)

    lines = [
        "# Opponent Model: Prediction and Identification (OPP-025)",
        "",
        f"Generated by `python -m catan_ai.cli.opponents_report` on {time.strftime('%Y-%m-%d')}. "
        f"catan_ai `{str(provenance()['catan_ai_commit'])[:7]}`. {len(records)} games of "
        f"`{args.data.name}/{args.split}`; one viewer per game (rotating seats) scores every "
        f"opponent decision with a real choice before seeing it ({len(rows):,} decisions); "
        f"likelihoods from one sampled world per decision; "
        f"{(time.perf_counter() - started) / 60:.1f} min.",
        "",
        "Components: " + ", ".join(f"`{n}`" for n in names) + ". `catanatron:AB:2` (AlphaBeta) "
        "is not a component, so it is a held-out policy.",
        "",
        "## Next-action prediction",
        "",
        "Mean log loss per decision (nats; lower is better). The mixture predicts with its "
        "posterior before each decision.",
        "",
        "| Opponent | Decisions | Mixture | " + " | ".join(f"`{n}`" for n in names) + " | "
        "Top-1 | Top-3 | Mean choices |",
        "|---|---|---|" + "---|" * len(names) + "---|---|---|",
    ]
    for policy, group in sorted(by_policy.items()):
        mixture = np.mean([-math.log(max(r["mixture"], 1e-300)) for r in group])
        per = np.mean([-np.log(np.maximum(r["components"], 1e-300)) for r in group], axis=0)
        top1 = np.mean([r["rank"] == 0 for r in group])
        top3 = np.mean([r["rank"] < 3 for r in group])
        choices = np.mean([r["choices"] for r in group])
        cells = " | ".join(f"{v:.3f}" for v in per)
        lines.append(
            f"| `{policy}` | {len(group):,} | **{mixture:.3f}** | {cells} | {top1:.1%} | "
            f"{top3:.1%} | {choices:.1f} |"
        )

    lines += [
        "",
        "## Identification",
        "",
        "Mean posterior weight on the opponent's true policy after n of its scored decisions "
        "(games where it made that many).",
        "",
        "| Opponent | True component | " + " | ".join(f"n = {n}" for n in CHECKPOINTS) + " |",
        "|---|---|" + "---|" * len(CHECKPOINTS),
    ]
    for policy, component in TRUE_COMPONENT.items():
        if policy not in by_policy:
            continue
        index = names.index(component)
        trajectories: dict[tuple[str, int], list[np.ndarray]] = defaultdict(list)
        for row in by_policy[policy]:
            trajectories[(row["game"], row["seat"])].append(
                np.log(np.maximum(row["components"], 1e-300))
            )
        columns: list[str] = []
        for n in CHECKPOINTS:
            weights = []
            for logs in trajectories.values():
                if len(logs) < n:
                    continue
                total = np.sum(logs[:n], axis=0)
                post = np.exp(total - total.max())
                weights.append(post[index] / post.sum())
            columns.append(f"{np.mean(weights):.2f} ({len(weights)})" if weights else "-")
        lines.append(f"| `{policy}` | `{component}` | " + " | ".join(columns) + " |")
    lines.append("")

    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {args.report}: {len(rows)} decisions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

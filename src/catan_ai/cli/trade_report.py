"""Trading behaviour and acceptance calibration (TRD-026..028, plan §8.5) -> reports/.

Plays a lineup in every seat rotation over a number of boards and reports:
offers, completed trades, counteroffers and errors (invalid transfers or
loops would surface as errors or truncation), wins by contestant, and the
calibration of each trading agent's predicted acceptance probabilities
against the responses that followed.

Example:
    python -m catan_ai.cli.trade_report --boards 25 --workers 11 \\
        --lineup trader:rules:heuristic trader:model:heuristic \\
                 negotiator:cooperative:heuristic negotiator:self-interested:heuristic
"""

import argparse
import time
from collections import Counter, defaultdict
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
from typing import Any

import numpy as np

from catan_ai.arena import Contestant, play_match
from catan_ai.engine import ActionKind
from catan_ai.provenance import REPO_ROOT, provenance

BINS = np.linspace(0, 1, 6)


def run_game(job: tuple[int, list[str]]) -> dict[str, Any]:
    seed, seating = job
    agents: dict[int, Any] = {}
    result, referee = play_match(
        f"trade-{seed}", seed, [Contestant(n) for n in seating], agent_sink=agents
    )
    events = referee.events
    kinds = Counter(e.event_type for e in events)
    rejections = [e for e in events if e.event_type == ActionKind.REJECT_TRADE]
    counters = sum(1 for e in rejections if e.public["action"]["params"])
    calibration = {
        seating[seat]: list(getattr(agent, "calibration", []))
        for seat, agent in agents.items()
        if hasattr(agent, "calibration")
    }
    confirms = [e for e in events if e.event_type == ActionKind.CONFIRM_TRADE]
    trades_by = Counter(seating[e.actor] for e in confirms if e.actor is not None)
    return {
        "winner": result.winner,
        "error": result.error,
        "truncated": result.truncated,
        "offers": kinds[ActionKind.OFFER_TRADE],
        "trades": kinds[ActionKind.CONFIRM_TRADE],
        "counters": counters,
        "trades_by": dict(trades_by),
        "calibration": calibration,
        "seconds": result.decision_seconds,
        "seating": seating,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lineup", nargs=4, required=True)
    parser.add_argument("--boards", type=int, default=25)
    parser.add_argument("--seed", type=int, default=700000)
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--report", type=Path, default=REPO_ROOT / "reports" / "trading.md")
    args = parser.parse_args(argv)

    started = time.perf_counter()
    jobs = [
        (args.seed + board, args.lineup[r:] + args.lineup[:r])
        for board in range(args.boards)
        for r in range(4)
    ]
    with ProcessPoolExecutor(args.workers) as pool:
        games = list(pool.map(run_game, jobs, chunksize=1))

    wins = Counter(g["winner"] for g in games)
    seconds: dict[str, list[float]] = defaultdict(list)
    for g in games:
        for seat, name in enumerate(g["seating"]):
            seconds[name].append(g["seconds"][seat])
    errors = sum(g["error"] is not None for g in games)
    truncated = sum(g["truncated"] for g in games)
    lines = [
        "# Trading: Behaviour and Acceptance Calibration (TRD-026 to TRD-028)",
        "",
        f"Generated by `python -m catan_ai.cli.trade_report` on {time.strftime('%Y-%m-%d')}. "
        f"catan_ai `{str(provenance()['catan_ai_commit'])[:7]}`. {len(games)} games "
        f"({args.boards} boards from seed {args.seed}, all four seat rotations); "
        f"{(time.perf_counter() - started) / 60:.1f} min.",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Games with an error (an invalid action or transfer) | **{errors}** |",
        f"| Games truncated (turn or decision limit) | {truncated} |",
        f"| Offers / completed trades / counteroffers per game | "
        f"{np.mean([g['offers'] for g in games]):.1f} / {np.mean([g['trades'] for g in games]):.1f}"
        f" / {np.mean([g['counters'] for g in games]):.1f} |",
        "",
        "| Contestant | Wins | Win share | Trades it confirmed per game | Seconds per game |",
        "|---|---|---|---|---|",
    ]
    for name in args.lineup:
        confirmed = np.mean([g["trades_by"].get(name, 0) for g in games])
        lines.append(
            f"| `{name}` | {wins[name]} | {wins[name] / len(games):.1%} | {confirmed:.1f} | "
            f"{np.mean(seconds[name]):.1f} |"
        )

    for name in args.lineup:
        pairs = [p for g in games for p in g["calibration"].get(name, [])]
        if not pairs:
            continue
        p = np.array([x[0] for x in pairs])
        hit = np.array([x[1] for x in pairs], dtype=np.float64)
        brier = float(np.mean((p - hit) ** 2))
        lines += [
            "",
            f"Acceptance calibration of `{name}`: P(a responder accepts) against its answer "
            f"({len(pairs):,} responses; Brier {brier:.4f}, base rate {hit.mean():.3f}).",
            "",
            "| Predicted | Responses | Mean predicted | Accepted |",
            "|---|---|---|---|",
        ]
        index = np.clip(np.digitize(p, BINS) - 1, 0, len(BINS) - 2)
        for b in range(len(BINS) - 1):
            mask = index == b
            if mask.any():
                lines.append(
                    f"| {BINS[b]:.1f} to {BINS[b + 1]:.1f} | {mask.sum():,} | "
                    f"{p[mask].mean():.3f} | {hit[mask].mean():.3f} |"
                )
    lines.append("")
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {args.report}: {len(games)} games, {errors} errors")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

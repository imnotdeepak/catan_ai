"""Reference ladder of Catanatron's built-in bots (ENG-011) -> reports/ladder.md.

Example:
    python -m catan_ai.cli.ladder --workers 11
    python -m catan_ai.cli.ladder --tiers fast --workers 11
"""

import argparse
import json
import statistics
import sys
import time
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from catan_ai.arena import Contestant, MatchResult, run_tournament
from catan_ai.evaluation import wilson_interval
from catan_ai.provenance import REPO_ROOT, provenance


def tier_section(tier: dict[str, Any], results: Sequence[MatchResult], minutes: float) -> str:
    names = list(dict.fromkeys(tier["lineup"]))
    rows = []
    for name in names:
        seats = [(r, s) for r in results for s, n in enumerate(r.seating) if n == name]
        wins = sum(r.winner_seat == s for r, s in seats)
        low, high = wilson_interval(wins, len(seats))
        by_seat = [sum(r.winner_seat == s for r, s in seats if s == k) for k in range(4)]
        decisions = sum(r.decisions[s] for r, s in seats)
        ms = sum(r.decision_seconds[s] for r, s in seats) / max(decisions, 1) * 1000
        privileged = "yes" if Contestant(name).privileged else "no"
        rows.append((wins / len(seats), name, privileged, len(seats), wins, low, high, by_seat, ms))
    rows.sort(reverse=True)

    decided = [r for r in results if r.winner_seat is not None]
    truncated = sum(r.truncated for r in results)
    errors = sum(r.error is not None for r in results)
    seat_wins = [sum(r.winner_seat == k for r in decided) for k in range(4)]
    turns = [r.num_turns for r in decided]
    lines = [
        f"## Tier `{tier['name']}`",
        "",
        f"Lineup {', '.join(f'`{n}`' for n in tier['lineup'])}; {tier['boards']} boards "
        f"from seed {tier['seed']}, each in all four seat rotations: **{len(results)} games**, "
        f"{len(decided)} decided, {truncated} truncated, {errors} errors; "
        f"{minutes:.1f} min wall time.",
        "",
        "| Rank | Bot | Privileged | Seat-games | Wins | Win rate | 95% CI | Wins by seat 0/1/2/3 "
        "| ms/decision |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for rank, (rate, name, priv, n, wins, low, high, by_seat, ms) in enumerate(rows, 1):
        lines.append(
            f"| {rank} | `{name}` | {priv} | {n} | {wins} | {rate:.1%} | "
            f"{low:.1%} to {high:.1%} | {'/'.join(map(str, by_seat))} | {ms:,.1f} |"
        )
    if turns:
        lines += [
            "",
            f"Turns per decided game: median {statistics.median(turns):.0f}, "
            f"range {min(turns)} to {max(turns)}. Wins by seat across the tier "
            f"(seat 0 moves first): {'/'.join(map(str, seat_wins))}.",
        ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=REPO_ROOT / "configs" / "ladder.json")
    parser.add_argument("--tiers", default=None, help="comma-separated tier names (default all)")
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "runs" / "ladder")
    parser.add_argument("--report", type=Path, default=REPO_ROOT / "reports" / "ladder.md")
    args = parser.parse_args(argv)

    config = json.loads(args.config.read_text(encoding="utf-8"))
    wanted = set(args.tiers.split(",")) if args.tiers else None
    sections = []
    for tier in config["tiers"]:
        if wanted is not None and tier["name"] not in wanted:
            continue
        print(f"tier {tier['name']}...", file=sys.stderr)
        started = time.perf_counter()
        results = run_tournament(
            [Contestant(n) for n in tier["lineup"]],
            tier["boards"],
            tier["seed"],
            out_dir=args.out / tier["name"],
            workers=args.workers,
        )
        sections.append(tier_section(tier, results, (time.perf_counter() - started) / 60))

    info = provenance()
    header = [
        "# Reference Ladder (ENG-011)",
        "",
        f"Generated by `python -m catan_ai.cli.ladder` on {time.strftime('%Y-%m-%d')} from "
        f"`configs/ladder.json`. Engine `{str(info['engine_commit'])[:7]}`, catan_ai "
        f"`{str(info['catan_ai_commit'])[:7]}`. Raw results and replays: `runs/ladder/` "
        "(not committed; rerun to regenerate).",
        "",
        "All built-in bots receive the full engine game, including hidden hands and the "
        "dev deck, so every result here is **privileged** (rules matrix H-01). The 95% "
        "intervals are Wilson intervals treating seat-games as independent; same-board "
        "games are correlated, so true uncertainty is larger (clustered intervals: EVAL-032). "
        "In a balanced four-player lineup, 25% is the even-strength win rate.",
        "",
    ]
    args.report.parent.mkdir(parents=True, exist_ok=True)
    body = "\n".join(header) + "\n" + "\n\n".join(sections) + "\n"
    args.report.write_text(body, encoding="utf-8")
    print(f"wrote {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

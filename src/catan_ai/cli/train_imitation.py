"""Train the imitation baseline (ML-014) -> checkpoints/, reports/imitation_training.md.

Trains on the `train` split, keeps the policy and value towers from their best
`dev` epochs, and reports that checkpoint on the untouched `holdout` split.

Example:
    python -m catan_ai.cli.train_imitation
"""

import argparse
import hashlib
import json
import time
from pathlib import Path
from typing import Any

from catan_ai.models.network import load_checkpoint
from catan_ai.provenance import REPO_ROOT, provenance
from catan_ai.training.dataset import load_split
from catan_ai.training.imitation import evaluate, train


def pct(x: float) -> str:
    return f"{x:.1%}"


def report(
    manifest: dict[str, Any],
    data_sha: str,
    settings: dict[str, Any],
    history: list[dict[str, Any]],
    holdout: dict[str, Any],
    checkpoint: Path,
    epochs: dict[str, Any],
    minutes: float,
) -> str:
    info = provenance()
    teachers = manifest["teachers"]
    base_rate = sum(n * rate for _, rate, n in holdout["reliability"]) / sum(
        n for *_, n in holdout["reliability"]
    )
    lines = [
        "# Imitation Baseline Training (ML-014)",
        "",
        f"Generated by `python -m catan_ai.cli.train_imitation` on {time.strftime('%Y-%m-%d')}. "
        f"catan_ai `{str(info['catan_ai_commit'])[:7]}`, "
        f"engine `{str(info['engine_commit'])[:7]}`. "
        f"Dataset manifest sha256 `{data_sha[:12]}`, features v{manifest['feature_version']}. "
        f"Checkpoint `{checkpoint.relative_to(REPO_ROOT).as_posix()}`: policy tower from epoch "
        f"{epochs['policy_epoch']}, value tower from epoch {epochs['value_epoch']} (each at "
        f"its lowest dev loss); {minutes:.1f} min on CPU.",
        "",
        "Inputs are player-view only. Teachers (`" + "`, `".join(teachers) + "`) read the full "
        "game, so some of their choices depend on hidden cards and cannot be fully imitated "
        "(plan §9.2).",
        "",
        "## Data",
        "",
        "| Split | Games | Decided | Samples | Mean candidates |",
        "|---|---|---|---|---|",
        *(
            f"| {name} | {s['games']:,} | {s['decided']:,} | {s['samples']:,} | "
            f"{s['candidates'] / max(s['samples'], 1):.1f} |"
            for name, s in manifest["splits"].items()
        ),
        "",
        "## Training",
        "",
        "Config: " + ", ".join(f"`{k}={v}`" for k, v in settings.items()) + ".",
        "",
        "| Epoch | Train policy | Train value | Dev policy | Dev top-1 | Dev value | Dev Brier "
        "| Dev ECE | s |",
        "|---|---|---|---|---|---|---|---|---|",
        *(
            f"| {r['epoch']} | {r['train_policy']:.3f} | {r['train_value']:.3f} | "
            f"{r['dev_policy_loss']:.3f} | {pct(r['dev_top1'])} | {r['dev_value_loss']:.3f} | "
            f"{r['dev_brier']:.4f} | {r['dev_ece']:.4f} | {r['seconds']:.0f} |"
            for r in history
        ),
        "",
        "## Holdout",
        "",
        "| Metric | Value | Reference |",
        "|---|---|---|",
        f"| Samples | {holdout['samples']:,} | |",
        f"| Policy top-1 (matches teacher) | **{pct(holdout['top1'])}** | uniform over legal "
        f"actions: {pct(holdout['uniform_top1'])} |",
        f"| Policy loss (NLL) | {holdout['policy_loss']:.3f} | |",
        f"| Value loss (4-way winner NLL) | {holdout['value_loss']:.3f} | uniform: 1.386 |",
        f"| Brier, P(I win) | {holdout['brier']:.4f} | base rate {base_rate:.3f}: "
        f"{base_rate * (1 - base_rate):.4f} |",
        f"| Expected calibration error | {holdout['ece']:.4f} | |",
        f"| Opponent hand MAE (cards per resource) | {holdout['hand_mae']:.3f} | |",
        f"| Final VP MAE | {holdout['points_mae']:.3f} | |",
        "",
        "Value reliability on holdout (P(I win), 10 bins):",
        "",
        "| Mean predicted | Observed | Samples |",
        "|---|---|---|",
        *(f"| {p:.3f} | {o:.3f} | {n:,} |" for p, o, n in holdout["reliability"]),
        "",
        "Top-1 by decision prompt:",
        "",
        "| Prompt | Top-1 | Samples |",
        "|---|---|---|",
        *(f"| {k} | {pct(a)} | {n:,} |" for k, (a, n) in holdout["top1_by_prompt"].items()),
        "",
        "Top-1 by the teacher's chosen action kind:",
        "",
        "| Action kind | Top-1 | Samples |",
        "|---|---|---|",
        *(f"| {k} | {pct(a)} | {n:,} |" for k, (a, n) in holdout["top1_by_label_kind"].items()),
        "",
        "Top-1 by teacher:",
        "",
        "| Teacher | Top-1 | Samples |",
        "|---|---|---|",
        *(
            f"| `{teachers[t]}` | {pct(a)} | {n:,} |"
            for t, (a, n) in holdout["top1_by_teacher"].items()
        ),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=REPO_ROOT / "configs" / "imitation.json")
    parser.add_argument("--data", type=Path, default=None, help="default data/<config name>")
    parser.add_argument("--out", type=Path, default=None, help="default checkpoints/<config name>")
    parser.add_argument(
        "--report", type=Path, default=REPO_ROOT / "reports" / "imitation_training.md"
    )
    args = parser.parse_args(argv)

    full = json.loads(args.config.read_text(encoding="utf-8"))
    settings = full["training"]
    args.data = args.data or REPO_ROOT / "data" / full["name"]
    args.out = args.out or REPO_ROOT / "checkpoints" / full["name"]
    manifest_bytes = (args.data / "manifest.json").read_bytes()
    manifest = json.loads(manifest_bytes)
    data_sha = hashlib.sha256(manifest_bytes).hexdigest()
    train_split, dev_split = load_split(args.data, "train"), load_split(args.data, "dev")
    print(f"train {len(train_split):,} samples, dev {len(dev_split):,}", flush=True)

    started = time.perf_counter()
    metadata = {"dataset_manifest_sha256": data_sha, "provenance": provenance()}
    _, history = train(
        settings, train_split, dev_split, args.out, metadata, log=lambda s: print(s, flush=True)
    )
    minutes = (time.perf_counter() - started) / 60
    del train_split

    checkpoint = args.out / "best.pt"
    net, saved = load_checkpoint(checkpoint)
    holdout = evaluate(net, load_split(args.data, "holdout"))
    (args.out / "holdout.json").write_text(json.dumps(holdout, indent=2), encoding="utf-8")
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(
        report(manifest, data_sha, settings, history, holdout, checkpoint, saved, minutes),
        encoding="utf-8",
    )
    print(f"holdout top-1 {holdout['top1']:.3f}, brier {holdout['brier']:.4f}")
    print(f"wrote {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

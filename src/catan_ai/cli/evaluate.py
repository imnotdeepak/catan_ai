"""Evaluate a learned model on the reference ladder (ML-015) -> reports/evaluation_0.2.md.

Example:
    python -m catan_ai.cli.evaluate --workers 11
"""

import argparse
import json
import time
from pathlib import Path
from typing import Any

from catan_ai.cli.ladder import run_tiers
from catan_ai.models.network import load_checkpoint
from catan_ai.provenance import REPO_ROOT, provenance


def describe(metadata: dict[str, Any]) -> str:
    """Provenance of an imitation or a PPO checkpoint."""
    if "policy_epoch" in metadata:
        return (
            f"policy epoch {metadata['policy_epoch']}, value epoch {metadata['value_epoch']}, "
            f"dataset manifest `{metadata['dataset_manifest_sha256'][:12]}`"
        )
    return f"PPO iteration {metadata.get('iteration')} from `{metadata.get('init')}`"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=REPO_ROOT / "configs" / "evaluation.json")
    parser.add_argument("--tiers", default=None, help="comma-separated tier names (default all)")
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "runs" / "evaluation")
    parser.add_argument("--report", type=Path, default=REPO_ROOT / "reports" / "evaluation_0.2.md")
    args = parser.parse_args(argv)

    config = json.loads(args.config.read_text(encoding="utf-8"))
    _, metadata = load_checkpoint(REPO_ROOT / config["model"])
    sections = run_tiers(config["tiers"], args.tiers, args.out, args.workers)

    info = provenance()
    header = [
        f"# {config.get('title', 'Release 0.2 Evaluation (ML-015)')}",
        "",
        f"Generated by `python -m catan_ai.cli.evaluate` on {time.strftime('%Y-%m-%d')} from "
        f"`{args.config.relative_to(REPO_ROOT).as_posix()}`. "
        f"Engine `{str(info['engine_commit'])[:7]}`, catan_ai "
        f"`{str(info['catan_ai_commit'])[:7]}`. Model `{config['model']}` ({describe(metadata)}).",
        "",
        "`model:` and `heuristic` seats decide from their own observation only. `catanatron:` "
        "seats read the full game and are **privileged** (rules matrix H-01). Board seeds are "
        "disjoint from the training data. The 95% intervals are Wilson intervals treating "
        "seat-games as independent; same-board games are correlated, so true uncertainty is "
        "larger (EVAL-032).",
        "",
    ]
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(
        "\n".join(header) + "\n" + "\n\n".join(sections) + "\n", encoding="utf-8"
    )
    print(f"wrote {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

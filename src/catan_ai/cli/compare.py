"""Head-to-head ablation of a candidate against a baseline (plan §11.2) -> reports/ablations/.

Candidate and baseline sit in the same four-player games with two fixed
opponents. Every board is played in all four seat rotations of both
[candidate, baseline, o1, o2] and [baseline, candidate, o1, o2], so each sits
in every seat and moves both before and after the other.

The test statistic is the candidate's share of the games won by either of the
two. Games won by an opponent carry no information about the pair and are
excluded. The p-value is an exact two-sided binomial test; the interval
resamples whole boards, since games on one board are correlated.

Example:
    python -m catan_ai.cli.compare --candidate model:checkpoints/x/best.pt --label x --workers 11
"""

import argparse
import time
from collections import defaultdict

from catan_ai.arena import Contestant, MatchResult, run_tournament
from catan_ai.evaluation import binomial_p_value, cluster_bootstrap_share, wilson_interval
from catan_ai.provenance import REPO_ROOT, provenance

CHAMPION = "model:champions/imitation-v1.pt"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--candidate", required=True)
    parser.add_argument("--baseline", default=CHAMPION)
    parser.add_argument("--label", required=True, help="report name")
    parser.add_argument("--opponents", default="catanatron:W,catanatron:VP")
    parser.add_argument("--boards", type=int, default=100)
    parser.add_argument("--seed", type=int, default=500000)
    parser.add_argument("--workers", type=int, default=1)
    args = parser.parse_args(argv)

    candidate, baseline = args.candidate, args.baseline
    opponents = args.opponents.split(",")
    started = time.perf_counter()
    results: list[MatchResult] = []
    for name, order in (
        ("candidate-first", [candidate, baseline]),
        ("baseline-first", [baseline, candidate]),
    ):
        lineup = [Contestant(n) for n in [*order, *opponents]]
        results += run_tournament(
            lineup,
            args.boards,
            args.seed,
            out_dir=REPO_ROOT / "runs" / "ablations" / args.label / name,
            workers=args.workers,
        )
    minutes = (time.perf_counter() - started) / 60

    by_board: dict[int, list[int]] = defaultdict(lambda: [0, 0])
    others = errors = 0
    first = [[0, 0], [0, 0]]  # [candidate moved first, baseline moved first] x [c wins, b wins]
    for r in results:
        errors += r.error is not None
        if r.winner is None:
            continue
        c_seat, b_seat = r.seating.index(candidate), r.seating.index(baseline)
        slot = 0 if c_seat < b_seat else 1
        if r.winner == candidate:
            by_board[r.seed][0] += 1
            first[slot][0] += 1
        elif r.winner == baseline:
            by_board[r.seed][1] += 1
            first[slot][1] += 1
        else:
            others += 1
    c_wins = sum(c for c, _ in by_board.values())
    b_wins = sum(b for _, b in by_board.values())
    decisive = c_wins + b_wins
    share = c_wins / decisive if decisive else 0.0
    low, high = cluster_bootstrap_share([(c, b) for c, b in by_board.values()])
    w_low, w_high = wilson_interval(c_wins, decisive)
    p = binomial_p_value(c_wins, decisive)
    verdict = (
        "**candidate better**"
        if p < 0.05 and share > 0.5
        else "**candidate worse**"
        if p < 0.05
        else "no significant difference"
    )

    info = provenance()
    lines = [
        f"# Ablation: {args.label}",
        "",
        f"Generated by `python -m catan_ai.cli.compare` on {time.strftime('%Y-%m-%d')}. "
        f"catan_ai `{str(info['catan_ai_commit'])[:7]}`, "
        f"engine `{str(info['engine_commit'])[:7]}`. "
        f"{minutes:.1f} min.",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Candidate | `{candidate}` |",
        f"| Baseline | `{baseline}` |",
        f"| Opponents | {', '.join(f'`{o}`' for o in opponents)} |",
        f"| Games | {len(results):,} ({args.boards} boards from seed {args.seed}, "
        f"8 seatings each), "
        f"{errors} errors |",
        f"| Won by candidate / baseline / opponents | {c_wins} / {b_wins} / {others} |",
        f"| **Candidate share of the pair's wins** | **{share:.1%}** |",
        f"| 95% interval, boards resampled | {low:.1%} to {high:.1%} |",
        f"| 95% Wilson interval (games independent) | {w_low:.1%} to {w_high:.1%} |",
        f"| Two-sided exact binomial p | {p:.4f} |",
        f"| Verdict (p < 0.05) | {verdict} |",
        f"| Share when candidate moves first / second | {_share(first[0])} / {_share(first[1])} |",
        "",
    ]
    report = REPO_ROOT / "reports" / "ablations" / f"{args.label}.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(lines), encoding="utf-8")
    print(f"candidate share {share:.3f} ({c_wins}/{decisive}), p={p:.4f}: {verdict}")
    print(f"wrote {report}")
    return 0


def _share(counts: list[int]) -> str:
    total = sum(counts)
    return f"{counts[0] / total:.1%} of {total}" if total else "n/a"


if __name__ == "__main__":
    raise SystemExit(main())

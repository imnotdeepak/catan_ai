"""How well each opening rule predicts real initial settlements (STR-018) -> reports/.

Replays the setup phase of recorded games and, at every initial settlement,
checks whether the rule's top site is the one the player actually chose. The
pair search predicts other seats with one such rule, so this measures its
snake-draft prediction against each kind of player.

Example:
    python -m catan_ai.cli.draft_accuracy --runs runs/ablations/features-v2
"""

import argparse
import json
import time
from collections import defaultdict
from pathlib import Path

from catan_ai.arena import replay
from catan_ai.engine import ActionKind, CanonicalAction
from catan_ai.observations import Referee
from catan_ai.opening.board import analyze
from catan_ai.opening.draft import SNAKE, best_site, placed
from catan_ai.opening.priors import RULES
from catan_ai.provenance import REPO_ROOT, provenance

SETUP_ACTIONS = 2 * len(SNAKE)  # a settlement and a road per pick


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--runs", type=Path, nargs="+", required=True, help="tournament dirs")
    parser.add_argument(
        "--report", type=Path, default=REPO_ROOT / "reports" / "draft_prediction.md"
    )
    args = parser.parse_args(argv)

    # hits[player][rule] = [first-round hits, first-round picks, second-round hits, picks]
    hits: dict[str, dict[str, list[int]]] = defaultdict(lambda: {r: [0, 0, 0, 0] for r in RULES})
    games = 0
    for run in args.runs:
        for path in sorted(run.rglob("replays/*.json")):
            record = json.loads(path.read_text(encoding="utf-8"))
            record["actions"] = record["actions"][:SETUP_ACTIONS]
            record["outcomes"] = record["outcomes"][:SETUP_ACTIONS]
            seating = record["seating"]

            def observe(
                seat: int, referee: Referee, action: CanonicalAction, seating: list[str] = seating
            ) -> None:
                if action.kind != ActionKind.BUILD_SETTLEMENT:
                    return
                analysis = analyze(referee.observe(seat))
                second = placed(analysis) >= len(SNAKE) // 2
                for rule, tally in hits[seating[seat]].items():
                    tally[2 * second] += best_site(analysis, seat, rule) == action.params[0]
                    tally[2 * second + 1] += 1

            replay(record, observe)
            games += 1

    info = provenance()
    rules = list(RULES)
    lines = [
        "# Snake-Draft Prediction (STR-018)",
        "",
        f"Generated by `python -m catan_ai.cli.draft_accuracy` on {time.strftime('%Y-%m-%d')}. "
        f"catan_ai `{str(info['catan_ai_commit'])[:7]}`. {games:,} games from "
        + ", ".join(f"`{r.resolve().relative_to(REPO_ROOT).as_posix()}`" for r in args.runs)
        + ".",
        "",
        "Share of initial settlements where the rule's top site is the player's actual choice "
        "(first round / second round). The pair search predicts other seats with `pips`.",
        "",
        "| Player | " + " | ".join(f"`{r}`" for r in rules) + " |",
        "|---|" + "---|" * len(rules),
    ]
    for player, by_rule in sorted(hits.items()):
        cells = [f"{a / max(n, 1):.0%} / {b / max(m, 1):.0%}" for a, n, b, m in by_rule.values()]
        lines.append(f"| `{player}` | " + " | ".join(cells) + " |")
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join([*lines, ""]), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

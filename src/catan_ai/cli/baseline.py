"""Release 0.1 baseline run (Sprint 1 deliverable 9) -> reports/baseline_report.md.

Plays the configured baseline lineup through the full firewalled path, then
rebuilds a sample of matches from their replay files and checks they match.

Example:
    python -m catan_ai.cli.baseline --workers 11
"""

import argparse
import json
import statistics
import sys
import time
from collections import Counter
from pathlib import Path

from catan_ai.arena import Contestant, replay, run_tournament
from catan_ai.provenance import REPO_ROOT, provenance


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=REPO_ROOT / "configs" / "ladder.json")
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "runs" / "baseline")
    parser.add_argument("--report", type=Path, default=REPO_ROOT / "reports" / "baseline_report.md")
    args = parser.parse_args(argv)

    config = json.loads(args.config.read_text(encoding="utf-8"))["baseline"]
    lineup = [Contestant(n) for n in config["lineup"]]
    started = time.perf_counter()
    results = run_tournament(
        lineup, config["boards"], config["seed"], out_dir=args.out, workers=args.workers
    )
    minutes = (time.perf_counter() - started) / 60

    print("verifying replays...", file=sys.stderr)
    checked = mismatches = 0
    for result in results[:: config["replay_check_every"]]:
        record = json.loads(
            (args.out / "replays" / f"{result.match_id}.json").read_text(encoding="utf-8")
        )
        rebuilt = replay(record)
        state = rebuilt.adapter.referee_game.state
        rebuilt_vp = tuple(int(state.player_state[f"P{s}_ACTUAL_VICTORY_POINTS"]) for s in range(4))
        same = (
            rebuilt.adapter.winner_seat == result.winner_seat
            and rebuilt_vp == result.victory_points
            and rebuilt.adapter.num_turns == result.num_turns
            and len(rebuilt.action_log) == sum(result.decisions)
        )
        checked += 1
        mismatches += not same

    decided = [r for r in results if r.winner_seat is not None]
    truncations = Counter(r.truncation_reason for r in results if r.truncated)
    errors = [r for r in results if r.error is not None]
    trades = 0
    for path in (args.out / "replays").glob("*.json"):
        actions = json.loads(path.read_text(encoding="utf-8"))["actions"]
        trades += sum(a["kind"] == "CONFIRM_TRADE" for a in actions)
    wins = Counter(r.winner for r in decided)
    decisions = sum(sum(r.decisions) for r in results)
    info = provenance()

    gate = [
        ("≥1,000 reproducible completed or explicitly truncated games", len(results) >= 1000),
        ("Zero illegal actions (arena errors)", not errors),
        ("Sampled replays rebuild the same game", checked > 0 and mismatches == 0),
    ]
    lines = [
        "# Release 0.1 Baseline Report",
        "",
        f"Generated by `python -m catan_ai.cli.baseline` on {time.strftime('%Y-%m-%d')}. "
        f"Engine `{str(info['engine_commit'])[:7]}`, catan_ai "
        f"`{str(info['catan_ai_commit'])[:7]}`. This is a **pipeline baseline, not a "
        "bot-strength result**: it shows the referee, observation firewall, arena and "
        "replay work at scale.",
        "",
        "## Run",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Lineup | {', '.join(f'`{c.name}`' for c in lineup)} (our agents decide from "
        "observations only; `catanatron:*` seats are privileged) |",
        f"| Boards x seat rotations | {config['boards']} x 4 from seed {config['seed']} |",
        f"| Games | {len(results):,} |",
        f"| Decided / truncated | {len(decided):,} / {sum(truncations.values())} "
        f"{dict(truncations) if truncations else ''} |",
        f"| Arena errors (illegal actions) | {len(errors)} |",
        f"| Decisions | {decisions:,} |",
        f"| Completed domestic trades | {trades:,} |",
        f"| Median turns (decided games) | "
        f"{statistics.median(r.num_turns for r in decided) if decided else 'n/a'} |",
        f"| Wall time | {minutes:.1f} min with {args.workers} worker(s) |",
        f"| Replays rebuilt and compared | {checked} (every "
        f"{config['replay_check_every']}th game), {mismatches} mismatches |",
        "",
        "Wins: " + ", ".join(f"`{name}` {n}" for name, n in wins.most_common()) + ".",
        "",
        "## Release 0.1 exit gate (plan §13)",
        "",
        "| Criterion | Status | Evidence |",
        "|---|---|---|",
        *(f"| {name} | {'Pass' if ok else '**FAIL**'} | this run |" for name, ok in gate),
        "| Zero observed hidden-information leaks | Pass | `tests/observations/` in CI |",
        "| Targeted rules tests | Pass | `tests/rules/`, `docs/rules-matrix.md` (no open "
        "rule deviations except D-08, counteroffers, scoped to TRD-027) |",
        "| Branch RNG independence | Pass | `tests/engine/test_branching.py` in CI |",
        "",
    ]
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.report}")
    return 0 if all(ok for _, ok in gate) else 1


if __name__ == "__main__":
    raise SystemExit(main())
